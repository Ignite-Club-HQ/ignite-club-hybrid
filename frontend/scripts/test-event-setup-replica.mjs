// Disposable canisters only; this test never uses a production identity or ID.
import assert from 'node:assert/strict';
import { PocketIc, PocketIcServer } from '@dfinity/pic';
import { Principal } from '@icp-sdk/core/principal';
import { IDL } from '@icp-sdk/core/candid';
import { idlFactory as eventsIdl } from '../src/lab/bindings/events_domain/declarations/events_domain.did.js';
import { idlFactory as clubIdl } from '../src/lab/bindings/club_domain/declarations/club_domain.did.js';
import { idlFactory as queueIdl } from '../src/lab/bindings/notification_queue/declarations/notification_queue.did.js';
const p = n => Principal.fromUint8Array(Uint8Array.from([n, 1]));
const governor = p(1), coach = p(2), member = p(3), stranger = p(4);
const ok = r => { assert.ok('Ok' in r, r.Err); return r.Ok; };
const server = await PocketIcServer.start({ binPath: process.env.POCKET_IC_BIN });
let pic;
try {
  pic = await PocketIc.create(server.getUrl());
  const setup = (idlFactory, wasm) => pic.setupCanister({ idlFactory, wasm, sender: governor, controllers: [governor], arg: IDL.encode([IDL.Principal], [governor]) });
  const events = await setup(eventsIdl, process.env.EVENTS_DOMAIN_WASM);
  const club = await setup(clubIdl, process.env.CLUB_DOMAIN_WASM);
  const queue = await setup(queueIdl, process.env.NOTIFICATION_QUEUE_WASM);
  for (const x of [events, club, queue]) x.actor.setPrincipal(governor);
  ok(await club.actor.create_club('club-a', 'Local test', 'local-test', [], []));
  const team = { id: 'team-a', name: 'Local team', club_id: 'club-a', is_active: true, is_shell: false, archived: false, playhq_auto_create_events: false };
  for (const field of ['division','gender','age_group','description','logo_url','team_type','deleted_at_ms','shell_claim_token','shell_claimed_at_ms','shell_claimed_by','shell_contact_email','shell_contact_name','shell_invited_by','playhq_team_id','playhq_competition_id','folder_id']) team[field] = [];
  ok(await club.actor.save_team(team));
  const acl = ok(await club.actor.export_acl());
  const roles = [{user:governor,role:'club_admin',club:['club-a'],team:[]},{user:coach,role:'coach',club:['club-a'],team:['team-a']},{user:member,role:'player',club:['club-a'],team:['team-a']}];
  ok(await club.actor.replace_acl(acl.acl_version,{...acl.acl, roles}));
  ok(await events.actor.set_club_domain_canister(club.canisterId));
  ok(await club.actor.set_events_domain_canister(events.canisterId));
  ok(await club.actor.set_notification_queue_canister(queue.canisterId));
  ok(await queue.actor.set_club_domain_canister(club.canisterId));
  const start = BigInt((await pic.getTime()) + 48 * 3_600_000);
  const input = { request_id: 'once', club_id:'club-a',team_id:['team-a'],title:'Local match',description:'Local round',event_type:'game',location:[],opponent:[],address:[],mini_league_id:[],rsvp_audience:['players_only'],adults_only:true,restricted_to_roles:[],target_team_ids:[],occurrences:[{starts_at_ms:start,ends_at_ms:start+3_600_000n},{starts_at_ms:start+604_800_000n,ends_at_ms:start+608_400_000n}],duties:[{duty:'Scorer',account_id:[coach.toText()]}],duty_team_id:[],reminder_hours:[12] };
  events.actor.setPrincipal(coach);
  const created = ok(await events.actor.create_event_with_setup(input));
  assert.equal(created.event_ids.length,2);
  assert.deepEqual(ok(await events.actor.create_event_with_setup(input)),created);
  assert.ok('Err' in await events.actor.create_event_with_setup({...input,title:'conflict'}));
  assert.equal(ok(await events.actor.read_account_list_duties(created.first_event_id)).length,1);
  assert.equal(ok(await events.actor.read_account_list_duties(created.event_ids[1])).length,0);
  ok(await events.actor.sync_active_game(['team-a'],'{}','{"sport":"basketball"}','device'));
  assert.equal(JSON.parse(ok(await events.actor.get_active_game(['team-a']))[0].pitch_state_json).sport,'basketball');
  assert.equal(ok(await events.actor.send_individual_event_reminder(created.first_event_id,[member.toText()],[])),1);
  assert.ok('Err' in await events.actor.send_individual_event_reminder(created.first_event_id,[member.toText()],[]));
  assert.ok('Err' in await events.actor.send_individual_event_reminder(created.first_event_id,[stranger.toText()],[]));
  queue.actor.setPrincipal(member);
  const inbox = ok(await queue.actor.list_inbox(member.toText(),['club-a'],20));
  assert.equal(inbox.length,1);
  assert.equal(inbox[0].kind,'event_reminder');
  events.actor.setPrincipal(stranger);
  assert.ok('Err' in await events.actor.create_event_with_setup({...input,request_id:'denied'}));
  assert.ok('Err' in await events.actor.read_event_cancellation_audience(created.first_event_id));
  club.actor.setPrincipal(stranger);
  assert.ok('Err' in await club.actor.relay_event_notice([member.toText()],'club-a','event_reminder','fake','fake',created.first_event_id));
  events.actor.setPrincipal(coach);
  ok(await events.actor.set_schedule_view('calendar'));
  assert.deepEqual(await events.actor.get_schedule_view(),['calendar']);
  events.actor.setPrincipal(member);
  assert.deepEqual(await events.actor.get_schedule_view(),[]);
  await pic.upgradeCanister({ canisterId: events.canisterId, wasm: process.env.EVENTS_DOMAIN_WASM, sender: governor, arg: IDL.encode([IDL.Principal],[governor]), upgradeModeOptions: { skip_pre_upgrade: [], wasm_memory_persistence: [{ keep: null }] } });
  events.actor.setPrincipal(coach);
  assert.deepEqual(await events.actor.get_schedule_view(),['calendar']);
  assert.deepEqual(ok(await events.actor.create_event_with_setup(input)),created);
  assert.ok('Err' in await events.actor.send_individual_event_reminder(created.first_event_id,[member.toText()],[]));
  console.log('PASS: complete setup, exact dates, first-occurrence duties, idempotent receipt, conflicts/foreign writes refused, queued reminder readback/cooldown, relay denial and private preference.');
} finally { await pic?.tearDown(); await server.stop(); }