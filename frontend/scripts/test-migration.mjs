import { Actor, HttpAgent } from '../node_modules/@icp-sdk/core/lib/esm/agent/index.js';
import { Principal } from '../node_modules/@icp-sdk/core/lib/esm/principal/index.js';
import { syntheticIdentity, CLUB_A } from '/workspaces/ignite-icp-lab/frontend/src/lab/syntheticIdentities.mjs';
import { idlFactory as clubLinks } from '/workspaces/ignite-icp-lab/frontend/src/lab/bindings/declarations/club_links.did.js';
import { idlFactory as router } from '/workspaces/ignite-icp-lab/frontend/src/lab/bindings/shard_router.did.js';
const host = process.env.MIGRATION_HOST ?? 'http://127.0.0.1:4973';
const rootKey = Uint8Array.from('308182301d060d2b0601040182dc7c0503010201060c2b0601040182dc7c05030201036100a587ac27884f235a91ddd86927eec11e09872417231b41ab8fb95605c633af9702849c0ad6929613392b39c715fc232c0a0d8eb00a1ea91985b3e440bc9d0b78a5872f96dae753f395cd6602516ad58748d698958976c6c25b86c55aa30a3af9'.match(/../g), x => parseInt(x, 16));
async function actor(factory, id, persona) {
  const agent = await HttpAgent.create({ host, identity: syntheticIdentity(persona), rootKey, shouldFetchRootKey: false, shouldSyncTime: false, useQueryNonces: true, retryTimes: 1 });
  return Actor.createActor(factory, { agent, canisterId: id });
}
const sourceId = process.env.MIGRATION_SOURCE_ID;
const destinationId = process.env.MIGRATION_DESTINATION_ID;
const routerId = process.env.MIGRATION_ROUTER_ID;
if (!sourceId || !destinationId || !routerId) throw new Error('Set MIGRATION_SOURCE_ID, MIGRATION_DESTINATION_ID and MIGRATION_ROUTER_ID');
const sourceAdmin = await actor(clubLinks, sourceId, 'club_admin');
const sourceGov = await actor(clubLinks, sourceId, 'governor');
const destGov = await actor(clubLinks, destinationId, 'governor');
const destAdmin = await actor(clubLinks, destinationId, 'club_admin');
const registry = await actor(router, routerId, 'governor');
const request = { request_id: '00000000-0000-4000-8000-000000000099', club: CLUB_A, expected_revision: 0n, operation: { Save: { id: [], draft: { title: 'Migrated', subtitle: [], url: 'https://example.com', icon: 'link', open_mode: 'browser', is_active: true } } } };
const seeded = await sourceAdmin.mutate(request);
if (!('Ok' in seeded)) throw new Error(`seed failed: ${seeded.Err}`);
const assigned = await registry.assign({ club_id: CLUB_A, shard: Principal.fromText(sourceId), expected_revision: 0n });
if (!('Ok' in assigned)) throw new Error(`assign failed: ${assigned.Err}`);
const sourcePrincipal = (await registry.get_route(CLUB_A)).Ok[0].shard;
const begin = await registry.begin_migration(CLUB_A, Principal.fromText(destinationId), assigned.Ok.revision);
if (!('Ok' in begin)) throw new Error(`begin failed: ${begin.Err}`);
const frozen = await sourceGov.freeze_club(CLUB_A, seeded.Ok.revision);
if (!('Ok' in frozen)) throw new Error(`freeze failed: ${frozen.Err}`);
const exported = await sourceGov.export_frozen_club(CLUB_A);
if (!('Ok' in exported)) throw new Error(`export failed: ${exported.Err}`);
const imported = await destGov.import_frozen_club(CLUB_A, exported.Ok);
if (!('Ok' in imported)) throw new Error(`import failed: ${imported.Err}`);
const stale = await sourceAdmin.mutate({ ...request, request_id: '00000000-0000-4000-8000-000000000098', expected_revision: seeded.Ok.revision });
if (!('Err' in stale) || stale.Err !== 'Club migration in progress') throw new Error(`stale write unexpectedly accepted: ${JSON.stringify(stale)}`);
const committed = await registry.commit_migration(CLUB_A, begin.Ok.migration_revision);
if (!('Ok' in committed)) throw new Error(`commit failed: ${committed.Err}`);
const route = await registry.get_route(CLUB_A);
if (!('Ok' in route) || !route.Ok.length || route.Ok[0].shard.toText() !== destinationId) throw new Error('route did not move to destination');
const listing = await destAdmin.list_links(CLUB_A, true);
if (!('Ok' in listing) || listing.Ok.links.length !== 1 || listing.Ok.links[0].draft.title !== 'Migrated') throw new Error('destination reconciliation failed');
console.log(JSON.stringify({ seeded: seeded.Ok.revision.toString(), frozen: frozen.Ok.toString(), imported: imported.Ok, stale: stale.Err, committed: committed.Ok.revision.toString(), destination: route.Ok[0].shard.toText(), links: listing.Ok.links.length }, null, 2));
