  vault.actor.setPrincipal(member);
  assert.equal(ok(await vault.actor.read_account_get_pinned_vault('group', conversation.id))[0].vault_file_id[0], 'new-file');
  assert.ok('Err' in await vault.actor.clear_pinned_vault('group', conversation.id));
  vault.actor.setPrincipal(outsider);
  assert.ok('Err' in await vault.actor.read_account_get_pinned_vault('group', conversation.id));
  vault.actor.setPrincipal(governor);
  const store = await pic.setupCanister({ idlFactory: storeIdl, wasm: resolve(root, 'backend/media_blob_store/.mops/.build/media_blob_store.wasm'), sender: governor, controllers: [governor], environmentVariables: [{ name: 'GOVERNOR_PRINCIPAL', value: governor.toText() }] });
  store.actor.setPrincipal(governor);
  ok(await store.actor.set_club_domain_canister(club.canisterId));
  ok(await store.actor.set_vault_authority(vault.canisterId));
  ok(await vault.actor.set_vault_stores([store.canisterId]));
  const path = 'clubs/club-a/vault/private-document';
  const payload = Uint8Array.from([1,2,3,4]);
  const upload = ok(await store.actor.begin_upload(path, 'application/pdf', 4n, 1));
  ok(await store.actor.put_chunk(upload, 0, payload));
  const bytes = ok(await store.actor.finalize_upload(upload));
  const ref = { canister: store.canisterId.toText(), path, content_hash: bytes.content_hash };
  const url = `https://${ref.canister}.raw.icp0.io/${path}`;
  assert.ok('Err' in await vault.actor.register_file('wrong-size', '', 'club-a', [], 'private.pdf', url, 5n, 'application/pdf', false, [ref], [], []));
  const saved = ok(await vault.actor.register_file('private-blob', '', 'club-a', [], 'private.pdf', url, 4n, 'application/pdf', false, [ref], [], []));
  assert.equal(ok(await vault.actor.register_file('private-blob', '', 'club-a', [], 'private.pdf', url, 4n, 'application/pdf', false, [ref], [], [])).id, saved.id);
