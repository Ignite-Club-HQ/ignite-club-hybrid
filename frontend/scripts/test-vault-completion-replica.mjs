  ok(await vault.actor.begin_file_cleanup(saved.id));
  assert.equal(ok(await vault.actor.begin_file_cleanup(saved.id)).id, saved.id);
  assert.ok('Err' in await vault.actor.delete_file_permanent(saved.id));
  assert.ok('Err' in await store.actor.delete_vault_blob(governor, path, ref.content_hash));
  vault.actor.setPrincipal(outsider);
  assert.ok('Err' in await vault.actor.resume_file_cleanup(saved.id));
  vault.actor.setPrincipal(governor);
