// Disposable local canisters only. Never reads live keys or production IDs.
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { PocketIc, PocketIcServer } from '@dfinity/pic';
import { Principal } from '@icp-sdk/core/principal';
import { IDL } from '@icp-sdk/core/candid';
import { idlFactory as vaultIdl } from '../src/lab/bindings/vault_domain/declarations/vault_domain.did.js';
import { idlFactory as clubIdl } from '../src/lab/bindings/club_domain/declarations/club_domain.did.js';
const root = resolve(import.meta.dirname, '../..');
const principal = n => Principal.fromUint8Array(Uint8Array.from([n, 1]));
const governor = principal(1), committee = principal(2), member = principal(3), outsider = principal(4);
const ok = r => { assert.ok('Ok' in r, r.Err); return r.Ok; };
const server = await PocketIcServer.start({ binPath: process.env.POCKET_IC_BIN });
let pic;
try {
  pic = await PocketIc.create(server.getUrl());
  const setup = (name, idlFactory) => pic.setupCanister({ idlFactory, wasm: resolve(root, `backend/${name}/.mops/.build/${name}.wasm`), sender: governor, controllers: [governor], arg: IDL.encode([IDL.Principal], [governor]) });
  const club = await setup('club_domain', clubIdl), vault = await setup('vault_domain', vaultIdl);
  club.actor.setPrincipal(governor); vault.actor.setPrincipal(governor);
  ok(await club.actor.create_club('club-a', 'Vault local acceptance', 'vault-local', [], []));
  const acl = ok(await club.actor.export_acl());
  const roles = [{ user: committee, role: 'committee_member', club: ['club-a'], team: [] }, { user: member, role: 'member', club: ['club-a'], team: [] }];
  ok(await club.actor.replace_acl(acl.acl_version, { ...acl.acl, roles }));
  ok(await vault.actor.set_club_domain_canister(club.canisterId));
  const folder = (id, parent, restrictions) => vault.actor.create_folder(id, 'club-a', [], parent, id, restrictions, [], [], 0, [], []);
  ok(await folder('private', [], ['committee_member']));
  ok(await folder('child', ['private'], []));
  const register = (id, destination = '') => vault.actor.register_file(id, destination, 'club-a', [], id, `https://example.com/${id}`, 0n, 'link/external', true, [], [], []);
  ok(await register('private-file', 'child'));
  vault.actor.setPrincipal(member);
  assert.deepEqual(ok(await vault.actor.read_account_get_folder('child')), []);
  assert.deepEqual(ok(await vault.actor.read_account_get_file('private-file')), []);
  vault.actor.setPrincipal(committee);
  assert.equal(ok(await vault.actor.read_account_get_file('private-file'))[0].id, 'private-file');
  vault.actor.setPrincipal(outsider);
  assert.ok('Err' in await vault.actor.read_vault_file_page('club-a', [], [], [], [], false, 0n, []));
  await assert.rejects(vault.actor.get_folder('child'), /protected consensus/);
  vault.actor.setPrincipal(governor);
  for (let i = 0; i < 205; i++) ok(await register(`public-${i}`));
  vault.actor.setPrincipal(member);
  const first = ok(await vault.actor.read_vault_file_page('club-a', [], [], [], [], false, 0n, []));
  assert.equal(first.next[0], 200n);
  const second = ok(await vault.actor.read_vault_file_page('club-a', [], [], [], [], false, first.next[0], [first.revision]));
  assert.equal(first.items.length + second.items.length, 205);
  vault.actor.setPrincipal(governor); ok(await register('new-file'));
  vault.actor.setPrincipal(member);
  assert.ok('Err' in await vault.actor.read_vault_file_page('club-a', [], [], [], [], false, 200n, [first.revision]));
  club.actor.setPrincipal(governor);
  const fresh = ok(await club.actor.export_acl());
  ok(await club.actor.replace_acl(fresh.acl_version, { ...fresh.acl, roles: roles.filter(r => !r.user.equals(committee)) }));
  vault.actor.setPrincipal(committee);
  assert.deepEqual(ok(await vault.actor.read_account_get_file('private-file')), []);
  vault.actor.setPrincipal(governor);
  assert.ok('Err' in await vault.actor.register_file('fake-bytes', '', 'club-a', [], 'fake', 'https://external.invalid/file', 10n, 'application/pdf', false, [], [], []));
  await pic.upgradeCanister({ canisterId: vault.canisterId, wasm: resolve(root, 'backend/vault_domain/.mops/.build/vault_domain.wasm'), sender: governor, arg: IDL.encode([IDL.Principal], [governor]), upgradeModeOptions: { skip_pre_upgrade: [], wasm_memory_persistence: [{ keep: null }] } });
  assert.equal(ok(await vault.actor.read_account_get_file('new-file'))[0].id, 'new-file');
  console.log('PASS: outsider/direct-query denial, live ancestor restrictions/revocation, 205-file paging, stale revision refusal, forged internal-file refusal, populated upgrade readback.');
} finally { await pic?.tearDown(); await server.stop(); }