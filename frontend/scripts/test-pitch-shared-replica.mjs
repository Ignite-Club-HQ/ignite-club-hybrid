// Disposable on-chain proof; never uses production IDs or identities.
import assert from 'node:assert/strict';
import { PocketIc, PocketIcServer } from '@dfinity/pic';
import { Principal } from '@icp-sdk/core/principal';
import { IDL } from '@icp-sdk/core/candid';
import { idlFactory as eventsIdl } from '../src/lab/bindings/events_domain/declarations/events_domain.did.js';
import { idlFactory as clubIdl } from '../src/lab/bindings/club_domain/declarations/club_domain.did.js';
import { idlFactory as queueIdl } from '../src/lab/bindings/notification_queue/declarations/notification_queue.did.js';
const p = n => Principal.fromUint8Array(Uint8Array.from([n, 1]));
const governor = p(1), coach = p(2), spectator = p(3), stranger = p(4);
const ok = r => { assert.ok('Ok' in r, r.Err); return r.Ok; };
const server = await PocketIcServer.start({ binPath: process.env.POCKET_IC_BIN });
let pic;
try {
  pic = await PocketIc.create(server.getUrl());
  const setup = (idlFactory, wasm) => pic.setupCanister({ idlFactory, wasm, sender: governor, controllers: [governor], arg: IDL.encode([IDL.Principal], [governor]) });
  const events = await setup(eventsIdl, process.env.EVENTS_DOMAIN_WASM);
  const club = await setup(clubIdl, process.env.CLUB_DOMAIN_WASM);
  const queue = await setup(queueIdl, process.env.NOTIFICATION_QUEUE_WASM);
  for (const x of [events, club, queue]) x.actor.setPrincipal(governor);
  ok(await club.actor.create_club('club-a', 'Local test', 'local-test', [], []));
  const team = { id: 'team-a', name: 'Local team', club_id: 'club-a', is_active: true, is_shell: false, archived: false, playhq_auto_create_events: false };
  for (const field of ['division','gender','age_group','description','logo_url','team_type','deleted_at_ms','shell_claim_token','shell_claimed_at_ms','shell_claimed_by','shell_contact_email','shell_contact_name','shell_invited_by','playhq_team_id','playhq_competition_id','folder_id']) team[field] = [];
  ok(await club.actor.save_team(team));
  const acl = ok(await club.actor.export_acl());
  const roles = [{user: governor,role:'club_admin',club:['club-a'],team:[]},{user:coach,role:'coach',club:['club-a'],team:['team-a']},{user:spectator,role:'member',club:['club-a'],team:['team-a']}];
  ok(await club.actor.replace_acl(acl.acl_version,{...acl.acl, roles}));
  ok(await events.actor.set_club_domain_canister(club.canisterId));
  ok(await club.actor.set_events_domain_canister(events.canisterId));
  ok(await club.actor.set_notification_queue_canister(queue.canisterId));
  ok(await queue.actor.set_club_domain_canister(club.canisterId));
  const board = ok(await events.actor.sync_shared_board('club-a','team-a',[], '{"players":[]}', 'device-a'));
  events.actor.setPrincipal(coach);
  assert.equal(ok(await events.actor.read_shared_board('club-a','team-a'))[0].updated_at_ms, board.updated_at_ms);
  const next = ok(await events.actor.sync_shared_board('club-a','team-a',[board.updated_at_ms], '{"players":[{"id":"p","position":{"x":12,"y":34}}]}','device-b'));
  assert.ok(next.updated_at_ms > board.updated_at_ms);
  assert.equal((await events.actor.sync_shared_board('club-a','team-a',[board.updated_at_ms], '{}','device-a')).Err,'State revision conflict');
  events.actor.setPrincipal(spectator);
  assert.equal(JSON.parse(ok(await events.actor.read_shared_board('club-a','team-a'))[0].pitch_state_json).players[0].position.x,12);
  assert.equal((await events.actor.sync_shared_board('club-a','team-a',[next.updated_at_ms],'{}','spectator')).Err,'Forbidden');
  events.actor.setPrincipal(stranger);
  assert.equal((await events.actor.read_shared_board('club-a','team-a')).Err,'Forbidden');
  events.actor.setPrincipal(governor);
  const event = ok(await events.actor.create_event('club-a',[], 'Local match','Local round', 'game',[],[],[],[],1000n,2000n,[],false,[],[]));
  const group = ok(await events.actor.create_event_group(event.id,'Local pitch',[],[],[],[]));
  ok(await events.actor.save_group_duty_slot(group.id,'ref','Referee',[coach.toText()]));
  ok(await events.actor.save_group_duty_slot(group.id,'subs','Subs Manager',[coach.toText()]));
  ok(await events.actor.save_group_duty_slot(group.id,'other','Other',[stranger.toText()]));
  assert.equal(ok(await events.actor.notify_group_pitch(group.id,'formation','2-3-1','once')),1);
  assert.equal(ok(await events.actor.notify_group_pitch(group.id,'formation','2-3-1','once')),0);
  queue.actor.setPrincipal(coach);
  const inbox = ok(await queue.actor.list_inbox(coach.toText(),['club-a'],20));
  assert.equal(inbox.length,1);
  assert.equal(inbox[0].body,'Formation changed to 2-3-1');
  events.actor.setPrincipal(stranger);
  assert.ok('Err' in await events.actor.notify_group_pitch(group.id,'substitution','','denied'));
  club.actor.setPrincipal(stranger);
  assert.equal((await club.actor.relay_group_pitch_alert([stranger.toText()],'club-a','pitch_board_substitution','fake','fake','event-group-fake')).Err,'Events authority required');
  console.log('PASS: peer readback, stale CAS refused, spectator and foreign access enforced, authoritative duties deduplicated, inbox readback and spoofed relay denied.');
} finally { await pic?.tearDown(); await server.stop(); }