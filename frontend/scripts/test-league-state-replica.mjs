// Local-only league clock, duty, private chat and named-invite authorization rehearsal.
import assert from 'node:assert/strict';
import { PocketIc, PocketIcServer } from '@dfinity/pic';
import { Principal } from '@icp-sdk/core/principal';
import { IDL } from '@icp-sdk/core/candid';
import { idlFactory as eventsIdl } from '../src/lab/bindings/events_domain/declarations/events_domain.did.js';
import { idlFactory as leagueIdl } from '../src/lab/bindings/mini_league_domain/declarations/mini_league_domain.did.js';
import { idlFactory as chatIdl } from '../src/lab/bindings/messaging_domain/declarations/messaging_domain.did.js';
import { idlFactory as clubIdl } from '../src/lab/bindings/club_domain/declarations/club_domain.did.js';
const governor = Principal.fromUint8Array(Uint8Array.from([1, 1]));
const parent = Principal.fromUint8Array(Uint8Array.from([2, 1]));
const stranger = Principal.fromUint8Array(Uint8Array.from([3, 1]));
const ok = r => { if ('Err' in r) throw new Error(r.Err); return r.Ok; };
const server = await PocketIcServer.start(); let pic;
try {
  pic = await PocketIc.create(server.getUrl());
  const ids = new Map();
  const setup = async (idlFactory, wasm) => { const result = await pic.setupCanister({ idlFactory, wasm, sender: governor, controllers: [governor], arg: IDL.encode([IDL.Principal], [governor]) }); ids.set(result.actor, result.canisterId); return result.actor; };
  const events = await setup(eventsIdl, process.env.EVENTS_DOMAIN_WASM);
  const destination = await setup(eventsIdl, process.env.EVENTS_DOMAIN_WASM);
  const league = await setup(leagueIdl, process.env.MINI_LEAGUE_DOMAIN_WASM);
  const chat = await setup(chatIdl, process.env.MESSAGING_DOMAIN_WASM);
  const club = await setup(clubIdl, process.env.CLUB_DOMAIN_WASM);
  club.setPrincipal(governor);
  ok(await club.replace_acl(0n, { clubs: ['club-a'], teams: [{ id: 'team-a', club: 'club-a' }],
    children: [{ id: 'legacy-child', club_id: ['club-a'], teams: ['team-a'], parent: [governor] }],
    guardians: [{ child: 'legacy-child', user: parent }], roles: [], exclusions: [] }));
  league.setPrincipal(governor); ok(await league.set_club_domain_canister(ids.get(club)));
  if (process.env.EVENTS_DOMAIN_OLD_WASM && process.env.MINI_LEAGUE_DOMAIN_OLD_WASM) {
    const oldEvents = await setup(eventsIdl, process.env.EVENTS_DOMAIN_OLD_WASM);
    const oldLeague = await setup(leagueIdl, process.env.MINI_LEAGUE_DOMAIN_OLD_WASM);
    oldEvents.setPrincipal(governor); oldLeague.setPrincipal(governor);
    const savedEvent = ok(await oldEvents.create_event('upgrade-club', [], 'Kept round', 'Round', 'game', [], [], [], [], 1000n, 2000n, [], false, [], []));
    const savedGroup = ok(await oldEvents.create_event_group(savedEvent.id, 'Kept pitch', [], [], [], []));
    ok(await oldEvents.sync_group_state(savedGroup.id, 0n, ['{"elapsedSeconds":75}'], []));
    const savedLeague = ok(await oldLeague.create_mini_league('upgrade-club', 'Kept league', [], [], 6, 3, 10, [], true));
    for (const [actor, wasm] of [[oldEvents, process.env.EVENTS_DOMAIN_WASM], [oldLeague, process.env.MINI_LEAGUE_DOMAIN_WASM]]) {
      await pic.upgradeCanister({ canisterId: ids.get(actor), wasm, sender: governor, arg: IDL.encode([IDL.Principal], [governor]), upgradeModeOptions: { skip_pre_upgrade: [], wasm_memory_persistence: [{ keep: null }] } });
    }
    assert.equal(ok(await oldEvents.get_event_group(savedGroup.id))[0].timer_state_json[0], '{"elapsedSeconds":75}');
    assert.equal(ok(await oldLeague.get_mini_league(savedLeague.id)).name, 'Kept league');
    ok(await oldEvents.set_mini_league_domain_canister(ids.get(oldLeague)));
    ok(await oldLeague.set_events_domain_canister(ids.get(oldEvents)));
    console.log('PASS: new authority migrations preserve existing event clocks and league rows through EOP upgrades.');
  }

  for (const a of [events, destination, league, chat]) a.setPrincipal(governor);
  const event = ok(await events.create_event('club-a', [], 'Round', 'League round', 'mini_league', [], [], [], [], 1000n, 2000n, [], false, [], []));
  const group = ok(await events.create_event_group(event.id, 'Pitch A', [], [], [], []));
  const first = ok(await events.save_group_duty_slot(group.id, 'slot-a', 'Referee', [parent.toText()]));
  const second = ok(await events.save_group_duty_slot(group.id, 'slot-b', 'Referee', []));
  assert.deepEqual(ok(await events.list_group_duties(group.id)).map(d => d.id), [first.id, second.id]);
  ok(await events.save_group_duty_slot(group.id, 'slot-b', 'Referee', [governor.toText()]));
  assert.deepEqual(ok(await events.list_group_duties(group.id)).find(d => d.id === 'slot-a').account_id, [parent.toText()]);
  ok(await events.remove_group_duty_slot(group.id, 'slot-b'));
  assert.deepEqual(ok(await events.list_group_duties(group.id)).map(d => d.id), ['slot-a']);
  const state = ok(await events.sync_group_state(group.id, 0n, ['{"elapsedSeconds":60}'], ['{"goals":[]}']));
  assert.equal(state.state_revision, 1n);
  assert.equal((await events.sync_group_state(group.id, 0n, [], [])).Err, 'State revision conflict');
  events.setPrincipal(stranger);
  assert.equal(ok(await events.read_event_group_club(group.id)).length, 0);
  assert.ok('Err' in await events.get_event_group(group.id));
  assert.ok('Err' in await events.sync_group_state(group.id, 1n, [], []));
  assert.ok('Err' in await events.save_group_duty_slot(group.id, 'slot-x', 'Referee', []));
  events.setPrincipal(governor);
  ok(await events.set_transfer_fence('club-a', true));
  assert.ok('Err' in await events.sync_group_state(group.id, 1n, [], []));
  ok(await destination.set_transfer_fence('club-a', true));
  ok(await destination.import_club_snapshot('club-a', ok(await events.export_club_snapshot('club-a'))));
  assert.equal(ok(await destination.get_event_group(group.id))[0].timer_state_json[0], '{"elapsedSeconds":60}');
  assert.equal(ok(await destination.get_event_group(group.id))[0].state_revision, 1n);
  assert.deepEqual(ok(await destination.list_group_duties(group.id)).map(d => d.id), ['slot-a']);
  const a = ok(await league.create_mini_league('club-a', 'A', [], [], 6, 3, 10, [], true));
  const b = ok(await league.create_mini_league('club-b', 'B', [], [], 6, 3, 10, [], true));
  const player = ok(await league.add_player(a.id, 'Player', [], [], [3], []));
  assert.ok('Err' in await league.create_invite(b.id, [player.id], []));
  const invite = ok(await league.create_invite(a.id, [player.id], []));
  league.setPrincipal(parent);
  assert.equal(ok(await league.get_player_invite_preview(invite.token))[0].league_name, 'A');
  assert.equal(ok(await league.claim_invite(invite.token, 'Ignored')).player_id, player.id);
  assert.equal(ok(await league.claim_invite(invite.token, 'Ignored')).player_id, player.id);
  assert.equal(ok(await league.get_player_guardian_status(player.id)).pending, false);
  league.setPrincipal(stranger);
  assert.ok('Err' in await league.claim_invite(invite.token, 'Steal'));
  assert.ok('Err' in await league.link_mini_league_guardian('arbitrary-child', stranger));
  // A named-invite claimant has no club-role mirror. Verify the real cross-domain path.
  events.setPrincipal(governor);
  ok(await events.set_transfer_fence('club-a', false));
  league.setPrincipal(governor);
  ok(await events.set_mini_league_domain_canister(ids.get(league)));
  ok(await league.set_events_domain_canister(ids.get(events)));
  const linked = ok(await events.create_event('club-a', [], 'Parent match', 'Round', 'mini_league', [], [], [], [a.id], 3000n, 4000n, [], false, [], []));
  const board = ok(await events.create_event_group(linked.id, 'Parent pitch', [], [], [], []));
  ok(await events.add_group_player(board.id, player.id, ['a']));
  ok(await events.sync_group_state(board.id, 0n, ['{"elapsedSeconds":90}'], ['{"goals":[]}']));
  const unrelated = ok(await events.create_event('club-a', [], 'Other league', 'Round', 'mini_league', [], [], [], [b.id], 3000n, 4000n, [], false, [], []));
  events.setPrincipal(parent);
  assert.equal(ok(await events.get_event_group(board.id))[0].timer_state_json[0], '{"elapsedSeconds":90}');
  assert.equal(ok(await events.read_event_group_club(board.id))[0], 'club-a');
  assert.equal(ok(await events.read_event_club(linked.id))[0], 'club-a');
  assert.equal(ok(await events.list_event_groups(linked.id))[0].id, board.id);
  assert.equal(ok(await events.list_group_players(board.id))[0].account_id, player.id);
  assert.deepEqual(ok(await events.list_group_duties(board.id)), []);
  assert.equal(ok(await events.get_group_edit_access(board.id)), false);
  assert.ok('Err' in await events.sync_group_state(board.id, 1n, [], []));
  const visible = ok(await events.list_events_multi(['club-a'], []));
  assert.ok(visible.some(e => e.id === linked.id));
  assert.ok(!visible.some(e => e.id === unrelated.id || e.id === event.id));
  league.setPrincipal(stranger);
  assert.equal(await league.can_read_league_matches(parent, a.id, 'club-a'), false);
  events.setPrincipal(stranger);
  assert.ok('Err' in await events.get_event_group(board.id));
  assert.deepEqual(await events.list_events(['club-a'], []), []);
  assert.ok('Err' in await events.set_mini_league_domain_canister(ids.get(league)));
  // Authority unavailable and removed player both deny previously admitted parents.
  events.setPrincipal(governor);
  ok(await events.set_mini_league_domain_canister(ids.get(destination)));
  events.setPrincipal(parent);
  assert.ok('Err' in await events.get_event_group(board.id));
  events.setPrincipal(governor);
  ok(await events.set_mini_league_domain_canister(ids.get(league)));
  league.setPrincipal(governor);
  ok(await league.remove_player(player.id));
  events.setPrincipal(parent);
  assert.ok('Err' in await events.get_event_group(board.id));
  assert.deepEqual(ok(await events.list_events_multi(['club-a'], [])), []);
  // Legacy child access comes from club_domain, not the stale player/guardian mirrors.
  league.setPrincipal(governor);
  const legacy = ok(await league.create_mini_league('club-a', 'Legacy', [], [], 6, 3, 10, [], true));
  const legacyPlayer = ok(await league.add_player(legacy.id, 'Legacy child', ['legacy-child'], [parent.toText()], [], []));
  ok(await league.link_mini_league_guardian('legacy-child', parent));
  assert.ok('Err' in await league.link_mini_league_guardian('legacy-child', stranger));
  events.setPrincipal(governor);
  const legacyEvent = ok(await events.create_event('club-a', [], 'Legacy match', 'Round', 'mini_league', [], [], [], [legacy.id], 3000n, 4000n, [], false, [], []));
  const legacyBoard = ok(await events.create_event_group(legacyEvent.id, 'Legacy pitch', [], [], [], []));
  league.setPrincipal(parent); events.setPrincipal(parent);
  assert.equal(ok(await league.get_mini_league(legacy.id)).id, legacy.id);
  assert.equal(ok(await league.get_player_guardian_status(legacyPlayer.id)).guardian_count, 1n);
  assert.equal(ok(await events.get_event_group(legacyBoard.id))[0].id, legacyBoard.id);
  league.setPrincipal(stranger);
  assert.ok('Err' in await league.get_player_guardian_status(legacyPlayer.id));
  club.setPrincipal(governor); ok(await club.unlink_guardian('legacy-child', parent));
  league.setPrincipal(parent); events.setPrincipal(parent);
  assert.ok('Err' in await league.get_mini_league(legacy.id));
  assert.ok('Err' in await league.get_player_guardian_status(legacyPlayer.id));
  assert.ok('Err' in await events.get_event_group(legacyBoard.id));
  league.setPrincipal(governor);
  assert.equal(ok(await league.get_player_guardian_status(legacyPlayer.id)).pending, true);
  assert.ok(!ok(await league.get_league_members(legacy.id)).some(u => u.user_id === parent.toText()));
  console.log('PASS: legacy parent access, private status, stale mirror denial and events board revocation after authoritative unlink.');
  chat.setPrincipal(governor);
  const privateChat = ok(await chat.ensure_mini_league_chat('club-a', a.id, 'A chat', [governor, parent]));
  assert.equal(ok(await chat.ensure_mini_league_chat('club-a', a.id, 'A chat', [governor, parent])).conversation_id, privateChat.conversation_id);
  chat.setPrincipal(parent);
  assert.equal(ok(await chat.get_mini_league_chat('club-a', a.id))[0].conversation_id, privateChat.conversation_id);
  chat.setPrincipal(stranger);
  assert.deepEqual(ok(await chat.get_mini_league_chat('club-a', a.id)), []);
  assert.ok('Err' in await chat.ensure_mini_league_chat('club-a', a.id, 'Steal', [stranger]));
  console.log('PASS: independent duplicate-name duties, CAS clock, stranger denial, transfer clock/duty preservation, named invite ownership/replay, guardian denial private league chat membership, live claimed-parent match access, read-only spectators, foreign-league denial, authority failure and revocation.');
} finally { await pic?.tearDown(); await server.stop(); }
