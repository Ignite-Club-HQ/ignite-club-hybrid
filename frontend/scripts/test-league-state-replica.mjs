// Local-only league clock, duty, private chat and named-invite authorization rehearsal.
import assert from 'node:assert/strict';
import { PocketIc, PocketIcServer } from '@dfinity/pic';
import { Principal } from '@icp-sdk/core/principal';
import { IDL } from '@icp-sdk/core/candid';
import { idlFactory as eventsIdl } from '../src/lab/bindings/events_domain/declarations/events_domain.did.js';
import { idlFactory as leagueIdl } from '../src/lab/bindings/mini_league_domain/declarations/mini_league_domain.did.js';
import { idlFactory as chatIdl } from '../src/lab/bindings/messaging_domain/declarations/messaging_domain.did.js';
const governor = Principal.fromUint8Array(Uint8Array.from([1, 1]));
const parent = Principal.fromUint8Array(Uint8Array.from([2, 1]));
const stranger = Principal.fromUint8Array(Uint8Array.from([3, 1]));
const ok = r => { if ('Err' in r) throw new Error(r.Err); return r.Ok; };
const server = await PocketIcServer.start(); let pic;
try {
  pic = await PocketIc.create(server.getUrl());
  const setup = async (idlFactory, wasm) => (await pic.setupCanister({ idlFactory, wasm, sender: governor, controllers: [governor], arg: IDL.encode([IDL.Principal], [governor]) })).actor;
  const events = await setup(eventsIdl, process.env.EVENTS_DOMAIN_WASM);
  const destination = await setup(eventsIdl, process.env.EVENTS_DOMAIN_WASM);
  const league = await setup(leagueIdl, process.env.MINI_LEAGUE_DOMAIN_WASM);
  const chat = await setup(chatIdl, process.env.MESSAGING_DOMAIN_WASM);
  for (const a of [events, destination, league, chat]) a.setPrincipal(governor);
  const event = ok(await events.create_event('club-a', [], 'Round', 'League round', 'mini_league', [], [], [], [], 1000n, 2000n, [], false, [], []));
  const group = ok(await events.create_event_group(event.id, 'Pitch A', [], [], [], []));
  const first = ok(await events.save_group_duty_slot(group.id, 'slot-a', 'Referee', [parent.toText()]));
  const second = ok(await events.save_group_duty_slot(group.id, 'slot-b', 'Referee', []));
  assert.deepEqual(ok(await events.list_group_duties(group.id)).map(d => d.id), [first.id, second.id]);
  ok(await events.save_group_duty_slot(group.id, 'slot-b', 'Referee', [governor.toText()]));
  assert.deepEqual(ok(await events.list_group_duties(group.id)).find(d => d.id === 'slot-a').account_id, [parent.toText()]);
  ok(await events.remove_group_duty_slot(group.id, 'slot-b'));
  assert.deepEqual(ok(await events.list_group_duties(group.id)).map(d => d.id), ['slot-a']);
  const state = ok(await events.sync_group_state(group.id, 0n, ['{"elapsedSeconds":60}'], ['{"goals":[]}']));
  assert.equal(state.state_revision, 1n);
  assert.equal((await events.sync_group_state(group.id, 0n, [], [])).Err, 'State revision conflict');
  events.setPrincipal(stranger);
  assert.equal(ok(await events.read_event_group_club(group.id)).length, 0);
  assert.ok('Err' in await events.get_event_group(group.id));
  assert.ok('Err' in await events.sync_group_state(group.id, 1n, [], []));
  assert.ok('Err' in await events.save_group_duty_slot(group.id, 'slot-x', 'Referee', []));
  events.setPrincipal(governor);
  ok(await events.set_transfer_fence('club-a', true));
  assert.ok('Err' in await events.sync_group_state(group.id, 1n, [], []));
  ok(await destination.set_transfer_fence('club-a', true));
  ok(await destination.import_club_snapshot('club-a', ok(await events.export_club_snapshot('club-a'))));
  assert.equal(ok(await destination.get_event_group(group.id))[0].timer_state_json[0], '{"elapsedSeconds":60}');
  assert.equal(ok(await destination.get_event_group(group.id))[0].state_revision, 1n);
  assert.deepEqual(ok(await destination.list_group_duties(group.id)).map(d => d.id), ['slot-a']);
  const a = ok(await league.create_mini_league('club-a', 'A', [], [], 6, 3, 10, [], true));
  const b = ok(await league.create_mini_league('club-b', 'B', [], [], 6, 3, 10, [], true));
  const player = ok(await league.add_player(a.id, 'Player', [], [], [3], []));
  assert.ok('Err' in await league.create_invite(b.id, [player.id], []));
  const invite = ok(await league.create_invite(a.id, [player.id], []));
  league.setPrincipal(parent);
  assert.equal(ok(await league.get_player_invite_preview(invite.token))[0].league_name, 'A');
  assert.equal(ok(await league.claim_invite(invite.token, 'Ignored')).player_id, player.id);
  assert.equal(ok(await league.claim_invite(invite.token, 'Ignored')).player_id, player.id);
  assert.equal(ok(await league.get_player_guardian_status(player.id)).pending, false);
  league.setPrincipal(stranger);
  assert.ok('Err' in await league.claim_invite(invite.token, 'Steal'));
  assert.ok('Err' in await league.link_mini_league_guardian('arbitrary-child', stranger));
  chat.setPrincipal(governor);
  const privateChat = ok(await chat.ensure_mini_league_chat('club-a', a.id, 'A chat', [governor, parent]));
  assert.equal(ok(await chat.ensure_mini_league_chat('club-a', a.id, 'A chat', [governor, parent])).conversation_id, privateChat.conversation_id);
  chat.setPrincipal(parent);
  assert.equal(ok(await chat.get_mini_league_chat('club-a', a.id))[0].conversation_id, privateChat.conversation_id);
  chat.setPrincipal(stranger);
  assert.deepEqual(ok(await chat.get_mini_league_chat('club-a', a.id)), []);
  assert.ok('Err' in await chat.ensure_mini_league_chat('club-a', a.id, 'Steal', [stranger]));
  console.log('PASS: independent duplicate-name duties, CAS clock, stranger denial, transfer clock/duty preservation, named invite ownership/replay, guardian denial and private league chat membership.');
} finally { await pic?.tearDown(); await server.stop(); }
