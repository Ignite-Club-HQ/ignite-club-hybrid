import assert from 'node:assert/strict';
import { Actor, HttpAgent } from '../node_modules/@icp-sdk/core/lib/esm/agent/index.js';
import { idlFactory } from '../src/lab/bindings/events_domain/declarations/events_domain.did.js';
import { syntheticIdentity } from '../src/lab/syntheticIdentities.mjs';

const host = process.env.EVENTS_HOST ?? 'http://127.0.0.1:4943';
const id = process.env.EVENTS_MOTOKO_ID;
if (!id) throw new Error('EVENTS_MOTOKO_ID is required');
const identity = syntheticIdentity('governor');
const agent = await HttpAgent.create({ host, identity, shouldFetchRootKey: true, shouldSyncTime: false, useQueryNonces: true, retryTimes: 1 });
const actor = Actor.createActor(idlFactory, { agent, canisterId: id });
const ok = result => { if ('Err' in result) throw new Error(result.Err); return result.Ok; };
const club = `motoko-events-${Date.now()}`;
const team = `motoko-team-${Date.now()}`;
const initialized = await actor.initialize();
if ('Err' in initialized && initialized.Err !== 'Already initialized') throw new Error(initialized.Err);
ok(await actor.grant_role(identity.getPrincipal(), 'club_admin', club, []));
const event = ok(await actor.create_event(club, [team], 'Motoko event', 'comparison', 10n, 20n));
const rsvp = ok(await actor.set_rsvp(event.id, 'account-motoko', 'yes'));
const attendance = ok(await actor.set_attendance(event.id, 'account-motoko', true, 'present'));
const duty = ok(await actor.set_duty(event.id, 'account-motoko', 'coach'));
const roster = ok(await actor.set_roster(event.id, 'account-motoko', ['child-motoko']));
const recurrence = ok(await actor.set_recurrence(event.id, 'weekly', 100n));
assert.equal(rsvp.event_id, event.id);
assert.equal(attendance.present, true);
assert.equal(duty.duty, 'coach');
assert.equal(roster.child_id[0], 'child-motoko');
assert.equal(recurrence.frequency, 'weekly');
const state = ok(await actor.export_state());
assert.equal(state.events.length, 1);
assert.equal(state.duties.length, 1);
console.log(JSON.stringify({ status: 'PASS', implementation: 'motoko', event: event.id, checks: ['event creation', 'RSVP', 'attendance', 'duty', 'roster', 'recurrence', 'durable export'] }, null, 2));
