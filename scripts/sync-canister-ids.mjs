// Copies the deployed mainnet canister ID table committed by the deploy
// workflow (deploy/mainnet/.icp/data/mappings/ic.ids.json) into the frontend
// source tree as a TypeScript module so targetRegistry.ts can bundle it as
// the build-time default when IGNITE_LIVE_ICP_CANISTER_IDS_JSON is not set.
// Missing source is fine — the generated module then holds an empty table,
// exactly the pre-deploy behaviour. A .ts module (not .json) is emitted
// because the frontend tsconfigs do not enable resolveJsonModule.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(projectRoot, "deploy", "mainnet", ".icp", "data", "mappings", "ic.ids.json");
const targetDir = path.join(projectRoot, "frontend", "src", "live", "generated");
const target = path.join(targetDir, "deployedCanisterIds.ts");

export function syncCanisterIds() {
  let ids = {};
  if (existsSync(source)) {
    ids = JSON.parse(readFileSync(source, "utf8"));
  }
  mkdirSync(targetDir, { recursive: true });
  const body =
    "// Generated by scripts/sync-canister-ids.mjs from\n" +
    "// deploy/mainnet/.icp/data/mappings/ic.ids.json — do not edit by hand.\n" +
    "// Re-run the sync (automatic in dev-preview/build-preview) after a deploy.\n" +
    `export const DEPLOYED_MAINNET_CANISTER_IDS: Record<string, string> = ${JSON.stringify(ids, null, 2)};\n`;
  writeFileSync(target, body);
  console.log(`synced ${Object.keys(ids).length} deployed canister IDs -> frontend/src/live/generated/deployedCanisterIds.ts`);
  return Object.keys(ids).length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  syncCanisterIds();
}
